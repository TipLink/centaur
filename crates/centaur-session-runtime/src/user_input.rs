use centaur_session_core::user_input::{
    SessionUserInputRequest, UserInputAnswers, UserInputQuestion, validate_user_input_questions,
};
use centaur_session_sqlx::UserInputClaim;

use super::*;

#[derive(Debug, Error)]
pub enum UserInputError {
    #[error("question request was not found")]
    NotFound,
    #[error("only the original requester may answer these questions")]
    Forbidden,
    #[error("{0}")]
    Conflict(String),
}

/// Only a caller with a question UI and an identified requester opts in. Override
/// any embedded flag so replayed input cannot advertise a capability the current
/// execution's caller did not supply.
pub(super) fn input_lines_with_user_input_support(
    input_lines: Vec<String>,
    metadata: Option<&Value>,
) -> Vec<String> {
    let enabled = metadata.is_some_and(|metadata| {
        metadata.get("supports_user_input").and_then(Value::as_bool) == Some(true)
            && metadata
                .get("user_id")
                .and_then(Value::as_str)
                .is_some_and(|id| !id.is_empty())
    });
    input_lines
        .into_iter()
        .map(|line| {
            let Ok(Value::Object(mut value)) = serde_json::from_str::<Value>(&line) else {
                return line;
            };
            if value.get("type").and_then(Value::as_str) != Some("user") {
                return line;
            }
            let trace = value.entry("trace_metadata").or_insert_with(|| json!({}));
            if !trace.is_object() {
                *trace = json!({});
            }
            trace["supports_user_input"] = json!(enabled);
            Value::Object(value).to_string()
        })
        .collect()
}

impl SessionRuntime {
    pub async fn list_user_input_requests(
        &self,
        thread_key: &ThreadKey,
    ) -> Result<Vec<SessionUserInputRequest>, SessionRuntimeError> {
        self.store.get_session(thread_key).await?;
        Ok(self.store.list_user_input_requests(thread_key).await?)
    }

    pub async fn get_user_input_request(
        &self,
        thread_key: &ThreadKey,
        request_id: &str,
    ) -> Result<SessionUserInputRequest, SessionRuntimeError> {
        self.store
            .get_user_input_request(thread_key, request_id)
            .await?
            .ok_or_else(|| UserInputError::NotFound.into())
    }

    pub async fn answer_user_input(
        &self,
        thread_key: &ThreadKey,
        execution_id: &str,
        request_id: &str,
        responder_user_id: &str,
        answers: &UserInputAnswers,
    ) -> Result<SessionUserInputRequest, SessionRuntimeError> {
        let request = match self
            .store
            .claim_user_input_answers(
                thread_key,
                execution_id,
                request_id,
                responder_user_id,
                answers,
            )
            .await?
        {
            UserInputClaim::Accepted(request) => request,
            UserInputClaim::NotFound => return Err(UserInputError::NotFound.into()),
            UserInputClaim::Forbidden => return Err(UserInputError::Forbidden.into()),
            UserInputClaim::Conflict(message) => {
                return Err(UserInputError::Conflict(message).into());
            }
            UserInputClaim::Invalid(message) => {
                return Err(SessionRuntimeError::BadRequest(message));
            }
        };
        if request.status == "resolved" {
            return Ok(request);
        }
        // The opaque live request id is generated by the adapter. A replaced
        // process cannot accept this answer, even if it resumes the same thread.
        let Some(execution) = self.store.active_execution_for_thread(thread_key).await? else {
            return Err(
                UserInputError::Conflict("execution is no longer active".to_owned()).into(),
            );
        };
        if execution.execution_id != execution_id || execution.status != ExecutionStatus::Running {
            return Err(
                UserInputError::Conflict("execution is no longer active".to_owned()).into(),
            );
        }
        let trace = SessionTraceContext::for_execution(
            None,
            execution_traceparent(&execution).map(ToOwned::to_owned),
            Some(execution_id),
        );
        let input_lines = input_lines_with_session_context(
            thread_key,
            &trace,
            &[json!({
                "type":"user_input_response",
                "thread_key":thread_key.as_str(),
                "execution_id":execution_id,
                "request_id":request_id,
                "answers":answers,
            })
            .to_string()],
        );
        let pipe = self
            .wait_for_active_steering_pipe(thread_key, execution_id)
            .await
            .map_err(UserInputError::Conflict)?;
        write_input_lines(&pipe, &input_lines, thread_key, execution_id, None).await?;
        // "submitted" means durably accepted and written, not yet acknowledged.
        // A retry sends the exact same answers; adapters acknowledge duplicates
        // without responding to the native tool twice.
        let request = self.get_user_input_request(thread_key, request_id).await?;
        if request.status == "cancelled" {
            return Err(UserInputError::Conflict("question is no longer active".to_owned()).into());
        }
        Ok(request)
    }
}

pub(super) async fn persist_user_input_output(
    ctx: &RuntimeContext,
    thread_key: &ThreadKey,
    execution: &SessionExecution,
    value: &Value,
) -> Result<(), SessionRuntimeError> {
    if !matches!(
        value.get("method").and_then(Value::as_str),
        Some("item/tool/requestUserInput" | "serverRequest/resolved")
    ) {
        return Ok(());
    }
    // Match the existing output event boundary: projections must not persist
    // credential-like text that the raw output event would redact.
    let safe_value = serde_json::from_str::<Value>(&redact_sensitive_text(&value.to_string()))
        .map_err(|error| SessionRuntimeError::BadRequest(error.to_string()))?;
    let value = &safe_value;
    let Some(params) = value.get("params") else {
        return Ok(());
    };
    match value.get("method").and_then(Value::as_str) {
        Some("item/tool/requestUserInput") => {
            if execution
                .metadata
                .get("supports_user_input")
                .and_then(Value::as_bool)
                != Some(true)
                || execution
                    .metadata
                    .get("user_id")
                    .and_then(Value::as_str)
                    .is_none_or(str::is_empty)
            {
                return Ok(());
            }
            let Some(request_id) = params.get("requestId").and_then(Value::as_str) else {
                return Ok(());
            };
            if Uuid::parse_str(request_id).is_err()
                || value.get("id").and_then(Value::as_str) != Some(request_id)
            {
                return Ok(());
            }
            let Ok(questions) = serde_json::from_value::<Vec<UserInputQuestion>>(
                params.get("questions").cloned().unwrap_or(Value::Null),
            ) else {
                return Ok(());
            };
            if validate_user_input_questions(&questions).is_err() {
                return Ok(());
            }
            let request = SessionUserInputRequest {
                request_id: request_id.to_owned(),
                execution_id: execution.execution_id.clone(),
                requester_user_id: execution
                    .metadata
                    .get("user_id")
                    .and_then(Value::as_str)
                    .filter(|id| !id.is_empty())
                    .map(ToOwned::to_owned),
                questions,
                status: "pending".to_owned(),
                answers: None,
            };
            ctx.store
                .record_user_input_request(thread_key, &request, &ctx.stdout_owner_id)
                .await?;
        }
        Some("serverRequest/resolved") => {
            if let Some(request_id) = params.get("requestId").and_then(Value::as_str) {
                let answered = params.get("reason").and_then(Value::as_str) == Some("answered");
                ctx.store
                    .resolve_user_input_request(
                        thread_key,
                        &execution.execution_id,
                        request_id,
                        &ctx.stdout_owner_id,
                        answered,
                    )
                    .await?;
            }
        }
        _ => {}
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn native_questions_require_caller_support_and_an_identified_requester() {
        let input = json!({"type":"user","trace_metadata":{"supports_user_input":true},
            "message":{"content":[]}})
        .to_string();
        for metadata in [
            None,
            Some(json!({"user_id":"U1"})),
            Some(json!({"supports_user_input":true})),
            Some(json!({"supports_user_input":false,"user_id":"U1"})),
        ] {
            let lines = input_lines_with_user_input_support(vec![input.clone()], metadata.as_ref());
            let line: Value = serde_json::from_str(&lines[0]).unwrap();
            assert_eq!(line["trace_metadata"]["supports_user_input"], false);
        }
        let lines = input_lines_with_user_input_support(
            vec![input],
            Some(&json!({
                "supports_user_input":true,"user_id":"U1"
            })),
        );
        let line: Value = serde_json::from_str(&lines[0]).unwrap();
        assert_eq!(line["trace_metadata"]["supports_user_input"], true);
    }
}
